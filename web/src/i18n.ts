const LEGACY: [RegExp, Key, string[]][] = [
  [/^送出提案 #(\S+)（评委蒙牌） tx (\S+)$/, 'mt.proposedJudge', ['id', 'tx']],
  [/^送出提案 #(\S+)（(.+)） tx (\S+)$/, 'mt.proposed', ['id', 'name', 'tx']],
  [/^提案失败：([\s\S]*)$/, 'mt.proposeFail', ['msg']],
  [/^approver 已核准 v2 codehash (\S+) tx (\S+)$/, 'mt.approved', ['c', 'tx']],
  [/^核准失败：([\s\S]*)$/, 'mt.approveFail', ['msg']],
  [/^提案送出中…$/, 'j.sending', []],
  [/^已送出（假事件）。判定后翻牌。$/, 'j.sentFake', []],
  [/^已送出提案 #(\S+)。判定后翻牌。$/, 'j.sentId', ['id']],
  [/^送出失败：([\s\S]*)$/, 'j.failed', ['msg']],
]
export function tLegacy(text: string): string {
  if (cur === 'zh-CN' || !text) return text
  for (const [re, key, names] of LEGACY) {
    const m = re.exec(text)
    if (m) return t(key, Object.fromEntries(names.map((n, i) => [n, m[i + 1]])))
  }
  return text
}
