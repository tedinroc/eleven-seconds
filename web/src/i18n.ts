// ---------- 状态与切换 ----------
let cur: Lang = 'zh-CN'
const listeners = new Set<() => void>()

export const isLang = (x: unknown): x is Lang => typeof x === 'string' && (LANGS as readonly string[]).includes(x)
export const lang = (): Lang => cur
export function onLangChange(fn: () => void) {
  listeners.add(fn)
}

function apply() {
  if (typeof document === 'undefined') return
  try {
    document.title = t('doc.title')
    if (document.documentElement) document.documentElement.lang = cur
  } catch {
    /* Node 自测的 DOM 替身没有这些属性 */
  }
}

/** 开页时呼叫一次：?lang= 优先，其次 localStorage，默认 zh-CN */
export function initLang(): Lang {
  let pick: Lang = 'zh-CN'
  try {
    const q = new URLSearchParams(globalThis.location?.search ?? '').get('lang')
    if (isLang(q)) pick = q
    else {
      const s = globalThis.localStorage?.getItem(LS_KEY)
      if (isLang(s)) pick = s
    }
  } catch {
    /* 无痕模式等：用默认 */
  }
  cur = pick
  apply()
  return cur
}

export function setLang(l: Lang, persist = true) {
  if (!isLang(l)) return
  cur = l
  apply()
  if (persist) {
    try {
      globalThis.localStorage?.setItem(LS_KEY, l)
    } catch {
      /* ignore */
    }
    // 网址上带了 ?lang= 时一并改掉，重新整理后仍是同一种语言（只改网址，不重载）
    try {
      const u = new URL(location.href)
      if (u.searchParams.has('lang')) {
        u.searchParams.set('lang', l)
        history.replaceState(history.state, '', u)
      }
    } catch {
      /* ignore */
    }
  }
  for (const fn of listeners) fn()
}

export function cycleLang(): Lang {
  setLang(LANGS[(LANGS.indexOf(cur) + 1) % LANGS.length])
  return cur
}

// ---------- 翻译 ----------
function fill(l: Lang, s: string, p?: Record<string, Param>): string {
  if (!p) return s
  return s.replace(/\{(\w+)\}/g, (all, name: string) => {
    const v = p[name]
    if (v === undefined || v === null) return all
    return typeof v === 'object' ? tIn(l, v.k, v.p) : String(v)
  })
}

/** 指定语言翻译（缺字时退回 zh-CN，再退回 key 本身） */
export function tIn(l: Lang, key: string, p?: Record<string, Param>): string {
  const s = DICT[l][key] ?? DICT['zh-CN'][key] ?? key
  return fill(l, s, p)
}

/** 当前语言翻译。参数原样代入：要进 innerHTML 的外部值由呼叫端先 esc() */
export function t(key: Key | DynKey, p?: Record<string, Param>): string {
  return tIn(cur, key, p)
}
export const tm = (m: Msg): string => tIn(cur, m.k, m.p)

/** 有就翻，没有就回传 fallback（规则 id、卡片、提案种类这类开放集合） */
export function tOr(key: Key | DynKey, fallback: string): string {
  const s = DICT[cur][key] ?? DICT['zh-CN'][key]
  return s ?? fallback
}

export const ruleText = (rule: string): string => tOr(`rule.${rule}`, rule)
export const stageName = (i: number): string => tOr(`stage.${i}`, String(i))
export const statusText = (st: number): string => tOr(`status.${st}`, '')
export const statusChip = (st: number): string => tOr(`statusChip.${st}`, '')
export const srcName = (s: string): string => tOr(`src.${s}`, s)

