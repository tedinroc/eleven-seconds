#!/usr/bin/env node
// Freezes the Arena's static inputs into src/generated/config.mjs (run by wrangler's [build] step
// before every dev/deploy):
//   - the Arena deployment: shared/deployments/10143-arena.json (ARENA_DEPLOYMENT=path overrides it,
//     used by the local anvil e2e; never point it at the live demo's 10143.json)
//   - ABIs (shared/abi/GuardedAdmin.json, DemoBTC.json), shared/rules.json, shared/gas.json
// Refuses to build when the deployment is missing fields or reuses the live demo's GuardedAdmin.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs'
import { dirname, resolve, isAbsolute } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const WORKER = resolve(HERE, '..')
const REPO = resolve(WORKER, '..', '..')
const SHARED = resolve(REPO, 'shared')

const depPath = process.env.ARENA_DEPLOYMENT
  ? (isAbsolute(process.env.ARENA_DEPLOYMENT) ? process.env.ARENA_DEPLOYMENT : resolve(process.cwd(), process.env.ARENA_DEPLOYMENT))
  : resolve(SHARED, 'deployments', '10143-arena.json')

function fail(msg) {
  console.error(`[bundle-config] ${msg}`)
  process.exit(1)
}
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'))
if (!existsSync(depPath)) fail(`Arena deployment not found: shared/deployments/10143-arena.json (or ARENA_DEPLOYMENT). Deploy the Arena contracts first (see arena/README.md).`)

const dep = readJson(depPath)
for (const k of ['chainId', 'guardedAdmin', 'proxy', 'owner', 'guardians', 'holders', 'impls', 'deployBlock']) {
  if (dep[k] == null) fail(`deployment json has no "${k}"`)
}
for (const k of ['v1', 'v2', 'evilMint', 'evilOwner', 'evilFee']) if (!dep.impls[k]) fail(`deployment json has no impls.${k}`)
if (!Array.isArray(dep.guardians) || dep.guardians.length < 3) fail('deployment json needs 3 guardians')

// The Arena must never share contracts with the live demo.
const live = resolve(SHARED, 'deployments', '10143.json')
if (existsSync(live) && resolve(depPath) !== live) {
  const l = readJson(live)
  if (String(l.guardedAdmin).toLowerCase() === String(dep.guardedAdmin).toLowerCase()) fail('Arena guardedAdmin equals the live demo guardedAdmin (10143.json); refusing to build')
}
if (resolve(depPath) === live) fail('ARENA_DEPLOYMENT points at the live demo deployment (10143.json); refusing to build')

const abiOf = (name) => {
  const j = readJson(resolve(SHARED, 'abi', `${name}.json`))
  return Array.isArray(j) ? j : j.abi
}
const config = {
  deployment: dep,
  deploymentFile: depPath.startsWith(REPO) ? depPath.slice(REPO.length + 1) : 'external',
  abi: { guardedAdmin: abiOf('GuardedAdmin'), token: abiOf('DemoBTC') },
  rules: readJson(resolve(SHARED, 'rules.json')),
  gas: readJson(resolve(SHARED, 'gas.json')),
  builtAt: new Date().toISOString(),
}
mkdirSync(resolve(WORKER, 'src', 'generated'), { recursive: true })
writeFileSync(
  resolve(WORKER, 'src', 'generated', 'config.mjs'),
  `// GENERATED by scripts/bundle-config.mjs at build time. Do not edit.\nexport default ${JSON.stringify(config)}\n`,
)
console.log(`[bundle-config] ${config.deploymentFile} chainId=${dep.chainId} guardedAdmin=${dep.guardedAdmin}`)
